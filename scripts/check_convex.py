"""Exercise the Convex review rules against the configured deployment.

Creates an isolated check submission (its own key and code, a fake clip id that no
worker has) and plays the worker's role itself, so no model call is made. Run it
while the API is stopped; a running worker would try to claim the check's queue.

    services/api/.venv/Scripts/python scripts/check_convex.py
"""

from __future__ import annotations

import hashlib
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "api"))

import httpx  # noqa: E402
from convex import ConvexClient, ConvexError  # noqa: E402

from app.config import Settings  # noqa: E402

results: list[tuple[str, bool]] = []


def check(name: str, ok: bool) -> None:
    results.append((name, ok))
    print(("PASS " if ok else "FAIL ") + name)


def refused(fn, code: str) -> bool:
    try:
        fn()
    except ConvexError as error:
        return code in str(error)
    return False


def main() -> int:
    settings = Settings()
    try:
        httpx.get(f"{settings.api_origin.rstrip('/')}/healthz", timeout=2)
        print("Stop the API first: its worker would claim the check's queued request.")
        return 2
    except httpx.HTTPError:
        pass
    c = ConvexClient(settings.convex_url)
    secret = settings.convex_worker_secret
    tag = secrets.token_hex(4)
    key, code = f"sub_check{tag}", secrets.token_urlsafe(9)
    access = {"key": key, "code": code}
    frames = [{"frameId": f"f{i:02d}", "tMs": i * 500} for i in range(1, 5)]
    box = {"x": 0.4, "y": 0.4, "w": 0.05, "h": 0.1}

    c.mutation("worker:createSubmission", {"secret": secret, "key": key, "playerKey": f"check-{tag}", "playerName": "Check player", "title": "Convex rule check", "accessHash": hashlib.sha256(code.encode()).hexdigest(), "rightsNote": "Generated by check_convex.py"})
    window_body = {"secret": secret, "submissionKey": key, "order": 1, "videoKey": f"vid_check{tag}", "manifestKey": f"man_check{tag}", "videoDurationMs": 10000, "startMs": 0, "endMs": 2000, "frames": frames, "assertedBy": "check"}
    check("a window needs an explicit player link", refused(lambda: c.mutation("worker:registerWindow", {**window_body, "linkStatement": "  "}), "link_required"))
    c.mutation("worker:registerWindow", {**window_body, "linkStatement": "Check link.", "initialRevision": {"key": f"rev_check{tag}", "anchors": [{"frameId": "f01", "state": "located", "source": "manual", "box": box}], "jerseyNote": "", "teamColorNote": "", "note": ""}})
    check("a wrong review code is refused", refused(lambda: c.query("review:get", {"key": key, "code": "wrong"}), "no_access"))
    check("a wrong worker secret is refused", refused(lambda: c.mutation("worker:claimNext", {"secret": "wrong", "workerId": "check"}), "worker_unauthorized"))

    review = c.query("review:get", access)
    window_id = review["windows"][0]["id"]
    first = c.mutation("review:queueAnalysis", {**access, "windowId": window_id, "reviewer": "check"})
    again = c.mutation("review:queueAnalysis", {**access, "windowId": window_id, "reviewer": "check"})
    check("queueing the same selection twice reuses the request", again["status"] == "already_queued" and again["requestId"] == first["requestId"])

    claim = None
    for _ in range(20):
        claim = c.mutation("worker:claimNext", {"secret": secret, "workerId": "check"})
        if not claim or claim["requestId"] == first["requestId"]:
            break
        print(f"Note: claimed another queued request {claim['requestId']}; its lease expires and the real worker claims it again.")
    if not claim or claim["requestId"] != first["requestId"]:
        print("FAIL could not claim the check request")
        return 1
    run = {"key": f"run_check{tag}", "model": "check", "promptVersion": "check", "schemaVersion": "1.1", "providerLabel": "synthetic", "costUsd": None, "inputTokens": None, "outputTokens": None, "latencyMs": None, "gaps": [], "issues": [], "noObservationReason": None, "createdAt": "2026-10-25T00:00:00Z"}
    observation = {"key": f"obs_check{tag}", "category": "passing_action", "startMs": 0, "endMs": 900, "seekMs": 0, "frameIds": ["f01"], "visibleAction": "Check action", "outcome": "not_observable", "evidenceStatus": "supported", "identityStatus": "clear_in_cited_frames", "limitations": [], "attributionHold": False, "holdReason": None, "holdFrameId": None}
    c.mutation("worker:publishResult", {"secret": secret, "requestId": claim["requestId"], "jobKey": "job_check", "cacheStatus": "live", "run": run, "observations": [observation]})
    moment = c.query("review:get", access)["moments"][0]
    check("a published observation starts as an AI suggestion", moment["status"] == "suggestion")
    c.mutation("review:decide", {**access, "observationId": moment["id"], "action": "accept", "reviewer": "check"})
    check("accepting it updates the summary", len(c.query("review:get", access)["summary"]["accepted"]) == 1)

    c.mutation("review:saveRevision", {**access, "windowId": window_id, "baseRevision": 1, "anchors": [{"frameId": "f01", "state": "located", "source": "manual", "box": box}, {"frameId": "f02", "state": "located", "source": "estimated", "box": box}], "jerseyNote": "", "teamColorNote": "", "note": "", "origin": "correction", "reviewer": "check"})
    check(
        "saving that estimate as manual without Confirm is refused",
        refused(lambda: c.mutation("review:saveRevision", {**access, "windowId": window_id, "baseRevision": 2, "anchors": [{"frameId": "f01", "state": "located", "source": "manual", "box": box}, {"frameId": "f02", "state": "located", "source": "manual", "box": box}], "jerseyNote": "", "teamColorNote": "", "note": "", "origin": "prepare", "reviewer": "check"}), "estimate_relabelled"),
    )
    check(
        "saving on top of an older selection is refused",
        refused(lambda: c.mutation("review:saveRevision", {**access, "windowId": window_id, "baseRevision": 1, "anchors": [{"frameId": "f01", "state": "located", "source": "manual", "box": box}], "jerseyNote": "", "teamColorNote": "", "note": "", "origin": "prepare", "reviewer": "check"}), "revision_conflict"),
    )
    after = c.query("review:get", access)
    check("a correction makes the old moment stale and drops it from the summary", after["moments"][0]["status"] == "stale" and after["summary"]["accepted"] == [])
    check("a stale moment cannot be decided", refused(lambda: c.mutation("review:decide", {**access, "observationId": moment["id"], "action": "accept", "reviewer": "check"}), "stale_observation"))

    late = c.mutation("worker:publishResult", {"secret": secret, "requestId": claim["requestId"], "jobKey": "job_check_late", "cacheStatus": "live", "run": {**run, "key": f"run_checklate{tag}"}, "observations": [{**observation, "key": f"obs_checklate{tag}"}]})
    final = c.query("review:get", access)
    check(
        "a late result for the old selection arrives outdated and stays out of the review",
        late["outdated"] is True and all(m["status"] == "stale" for m in final["moments"]) and final["windows"][0]["currentRunId"] is None,
    )

    scout_key, scout_code = f"sub_scout{tag}", secrets.token_urlsafe(9)
    scout_access = {"key": scout_key, "code": scout_code}
    c.mutation("worker:createSubmission", {"secret": secret, "key": scout_key, "playerKey": f"scout-{tag}", "playerName": "Scout check", "title": "Scout lifecycle", "accessHash": hashlib.sha256(scout_code.encode()).hexdigest(), "rightsNote": "Generated by check_convex.py"})
    c.mutation("worker:registerWindow", {**window_body, "submissionKey": scout_key, "manifestKey": f"man_scout{tag}", "videoKey": f"vid_scout{tag}", "kind": "scout", "linkStatement": "Scout link.", "initialRevision": {"key": f"rev_scout{tag}", "anchors": [{"frameId": "f01", "state": "located", "source": "manual", "box": box}], "jerseyNote": "", "teamColorNote": "", "note": ""}})
    scout_window = c.query("review:get", scout_access)["windows"][0]["id"]
    queued = c.mutation("review:queueAnalysis", {**scout_access, "windowId": scout_window, "reviewer": "check"})
    scout_claim = None
    for _ in range(20):
        scout_claim = c.mutation("worker:claimNext", {"secret": secret, "workerId": "check"})
        if not scout_claim or scout_claim["requestId"] == queued["requestId"]:
            break
    check("a scout request is claimed as a scout analysis", bool(scout_claim) and scout_claim["kind"] == "scout")
    if scout_claim and scout_claim["requestId"] == queued["requestId"]:
        before = c.mutation("worker:progress", {"secret": secret, "requestId": scout_claim["requestId"], "stage": "tracking", "jobKey": "job_scout", "progress": {"phase": "tracking", "chunksDone": 1, "chunksTotal": 2}})
        c.mutation("review:cancelAnalysis", {**scout_access, "windowId": scout_window})
        after_cancel = c.mutation("worker:progress", {"secret": secret, "requestId": scout_claim["requestId"], "stage": "tracking", "jobKey": "job_scout", "progress": {"phase": "tracking", "chunksDone": 1, "chunksTotal": 2}})
        check("cancel is reported to the worker on the next progress call", before["cancelRequested"] is False and after_cancel["cancelRequested"] is True)
        run_id = c.mutation("worker:openRun", {"secret": secret, "requestId": scout_claim["requestId"], "runKey": f"scout:{tag}", "model": "check", "promptVersion": "scout-v1", "schemaVersion": "2.0"})
        c.mutation("worker:addObservations", {"secret": secret, "runId": run_id, "observations": [
            {**observation, "key": f"sc_pass_a_{tag}", "action": "pass", "outcomeDetail": "completed", "outcome": "completed_visible", "visibleAction": "Plays a short pass.", "startMs": 1000, "endMs": 1800},
            {**observation, "key": f"sc_pass_b_{tag}", "action": "pass", "outcomeDetail": "unclear", "outcome": "not_observable", "visibleAction": "Plays a pass.", "startMs": 4000, "endMs": 4800},
        ]})
        c.mutation("worker:addCorrection", {"secret": secret, "requestId": scout_claim["requestId"], "frameId": "f03", "tMs": 1500, "reason": "The track was lost.", "boxes": [{"trackId": 4, "box": box, "confidence": 0.8}]})
        c.mutation("worker:closeRun", {"secret": secret, "requestId": scout_claim["requestId"], "runId": run_id, "state": "partial", "note": "1 of 2 candidates inspected.", "jobKey": "job_scout"})
        opened = c.query("review:get", scout_access)
        check("scout events produce a finding and a correction", len(opened["brief"]["findings"]) == 1 and "2 passes" in opened["brief"]["findings"][0]["text"] and opened["corrections"][0]["frameId"] == "f03")
        for moment in opened["moments"]:
            c.mutation("review:decide", {**scout_access, "observationId": moment["id"], "action": "reject", "reason": "Not this player.", "reviewer": "check"})
        cleared = c.query("review:get", scout_access)
        check("rejecting both events clears the finding", cleared["brief"]["findings"] == [] and cleared["runs"][0]["state"] == "partial")

    failed = [name for name, ok in results if not ok]
    print(f"{len(results) - len(failed)}/{len(results)} Convex checks passed. Check submission {key} stays in the deployment, reachable only with its code.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
